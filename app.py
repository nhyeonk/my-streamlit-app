    """앱 시작 시 기본 백서 체인 (한 번만 생성되어 모든 세션이 공유)
    - 저장소에 백서 PDF가 있으면 고도화 파이프라인으로 생성
    - PDF가 없으면 Colab에서 만든 chroma_db 사용(기본 검색)"""
    pdf = find_file(DEFAULT_PDF)
