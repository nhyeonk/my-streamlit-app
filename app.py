def _bi(text):
    t = re.sub(r"[^가-힣A-Za-z0-9]", "", text)
    return {t[i:i + 2] for i in range(len(t) - 1)}


def match_seniors(query, top=2):
    """02장의 각 선배 절(1)~)과 질문자 정보를 비교해 가장 닮은 절 찾기"""
    idx = st.session_state.get("index")
    if not idx:
        return []
    cands = {k: v for k, v in idx.parent_text.items()
             if k.startswith("02") and re.search(r"›\s*\d{1,2}\)", k)}
    if not cands:
        return []
    grams = {k: _bi(v) for k, v in cands.items()}
    df = {}
    for g in grams.values():
        for b in g:
            df[b] = df.get(b, 0) + 1
    qb = _bi(query)
    scores = []
    for k, g in grams.items():
        s = sum(math.log(1 + len(cands) / df[b]) for b in g & qb)
        scores.append((s / (len(g) ** 0.25 + 1e-9), k))
    scores.sort(reverse=True)
    return [(k, cands[k]) for s, k in scores[:top] if s > 0]


