def section_text(keyword, limit=1500):
    """백서에서 제목에 keyword가 들어간 절 내용 (없으면 빈 문자열)"""
    idx = st.session_state.get("index")
    if not idx:
        return ""
    for title, text in idx.text.items():
        if keyword in title:
            return clean_text(text)[:limit]
    return ""


def make_til(learned, stuck, goal):
    ctx = section_text("TIL") + "\n\n" + section_text("인출 연습")
